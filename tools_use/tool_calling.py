
# Import load_dotenv to load environment variables from the .env file
from dotenv import load_dotenv

# Load the variables from .env
# For example: MISTRAL_API_KEY=your_api_key
load_dotenv()


# Import Mistral's chat model from LangChain
from langchain_mistralai import ChatMistralAI

# Import the tool decorator used to create a LangChain tool
from langchain.tools import tool

# Import ToolMessage to send the tool result back to the LLM
from langchain_core.messages import ToolMessage

from langchain_core.messages import HumanMessage
# Import Rich's print function for better terminal output
from rich import print


# ============================================================
# 1. CREATE A TOOL
# ============================================================

# @tool converts the normal Python function into a
# LangChain tool that can be called by the LLM.
@tool
def get_text_length(text: str) -> int:
    """Returns the number of characters in the given text."""
    
    # len() counts the number of characters in the text
    return len(text)

tools = {
    "get_text_length": get_text_length
}

# ============================================================
# 2. CREATE THE LLM
# ============================================================

# Create a Mistral chat model.
# The API key is taken automatically from the environment.
llm = ChatMistralAI(
    model="mistral-small-2603"
)


# ============================================================
# 3. BIND THE TOOL TO THE LLM
# ============================================================

# Make the get_text_length tool available to the LLM.
#
# Note:
# bind_tools() does not execute the tool.
# It only tells the LLM that this tool is available.
llm_with_tool = llm.bind_tools(
    [get_text_length]
)

